#!/usr/bin/env bash
# 一键打包「可直接发给朋友」的安装包。
#
# 解决的核心问题：微信/QQ/邮件在传输时，如果对方已有同名文件，会自动改名成
# xxx.apk.1 / xxx.apk.2。本脚本用「版本号 + 日期 + 内容哈希」做文件名，保证
# 每次发出的文件名唯一，永远不会撞名；同时额外产出 ZIP 包与 SHA-256 校验文件。
#
# 用法：
#   ./share.sh              打包 release 版本（发给朋友用这个）
#   ./share.sh --debug      打包 debug 版本
#   ./share.sh --skip-build 只重新命名/打包现有 APK（不重新编译，仅应急用）
set -euo pipefail

PROJ_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJ_DIR"

VARIANT="release"
if [[ "${1:-}" == "--debug" ]]; then
  VARIANT="debug"
fi

# ---- 工具链：环境变量 / local.properties → 项目自带 gradlew ----
# 不把任何本机绝对路径写进版本库；clone 后用 ANDROID_HOME + ./gradlew 即可构建。
get_prop() {
  local f="$PROJ_DIR/local.properties"
  [ -f "$f" ] || { printf ''; return 0; }
  local v
  v=$(grep -E "^[[:space:]]*$1=" "$f" | head -1 | cut -d= -f2- | tr -d '\r' || true)
  printf '%s' "$v"
}
TOOLCHAIN="${ADSKIP_TOOLCHAIN:-$(get_prop toolchain.dir)}"
if [ -z "${JAVA_HOME:-}" ] && [ -n "$TOOLCHAIN" ] && [ -d "$TOOLCHAIN/jdk17" ]; then
  export JAVA_HOME="$TOOLCHAIN/jdk17"
fi
if [ -n "${JAVA_HOME:-}" ]; then export PATH="$JAVA_HOME/bin:$PATH"; fi
if [ -n "${ADSKIP_GRADLE:-}" ]; then
  GRADLE="$ADSKIP_GRADLE"
elif [ -n "$TOOLCHAIN" ] && [ -f "$TOOLCHAIN/gradle-8.4/bin/gradle.bat" ]; then
  GRADLE="$TOOLCHAIN/gradle-8.4/bin/gradle.bat"
elif [ -f "$PROJ_DIR/gradlew" ]; then
  GRADLE="$PROJ_DIR/gradlew"
else
  GRADLE="gradle"
fi

SRC_APK="$PROJ_DIR/app/build/outputs/apk/$VARIANT/app-$VARIANT.apk"

# 必须每次都重新编译。
# 以前写成「APK 不存在才构建」，而 Gradle 的产物一直在 build/outputs 里：
# 改完源码再跑本脚本，打出来的仍是上一版二进制，文件名却写着新版本号，
# 这种包发出去之后根本没法从版本号判断里面是什么代码。
# 顺带把广告测试台一起编译，否则 clean 之后 ZIP 里会缺这个 APK。
if [[ "${2:-}" == "--skip-build" || "${1:-}" == "--skip-build" ]]; then
  echo "[1/4] 跳过构建（--skip-build）"
else
  echo "[1/4] 正在构建 $VARIANT + 广告测试台 ..."
  "$GRADLE" -p "$PROJ_DIR" "assemble${VARIANT^}" ":adsample:assembleDebug" \
    --console=plain 2>&1 | tail -5
fi
[[ -f "$SRC_APK" ]] || { echo "构建失败：找不到 $SRC_APK"; exit 1; }

# ---- 版本号 + 日期 + 内容哈希：文件名天然唯一 ----
VERSION=$(grep -oP 'versionName\s*=\s*"\K[^"]+' app/build.gradle.kts | head -1)
VERSION="${VERSION:-1.0.0}"
HASH=$(sha256sum "$SRC_APK" | cut -c1-8)
STAMP=$(date +%Y%m%d)
FILENAME="秒跳-AdSkipper-v${VERSION}-${STAMP}-${HASH}.apk"
ZIPNAME="秒跳-AdSkipper-v${VERSION}-${STAMP}.zip"

OUT_DIR="$PROJ_DIR/dist"
mkdir -p "$OUT_DIR"
cd "$OUT_DIR"

echo "[2/4] 生成唯一文件名 ..."
cp -f "$SRC_APK" "$FILENAME"
SHA=$(sha256sum "$FILENAME" | awk '{print $1}')
printf '%s  %s\n' "$SHA" "$FILENAME" > "$FILENAME.sha256"

echo "[3/4] 生成安装说明 ..."
cat > "安装说明.txt" <<EOF
【秒跳 AdSkipper】v${VERSION} 安装说明
=====================================

■ 本版（v1.3.1）：全量代码复查，修掉一批藏得比较深的缺陷
1) 规则命中时所有候选共用同一个临时「位置」对象
   后果是多个候选被判成同一个位置、只留 1 条，自检面板显示的按钮位置也全是错的。
2) 任意一次扫描异常会把服务永久切回主线程
   主线程读界面是同步调用，实测会把服务直接卡死；现在异常只影响本轮，
   下一轮自动恢复，而且界面树切换瞬间的节点失效也不会让整轮扫描崩掉。
3) 两个线程可能同时投递扫描任务（窗口事件 vs 扫描自排）
   改成原子闸门，避免同一棵界面树被并发读取、重复点击。
4) 打包脚本以前只在 APK 不存在时才编译
   改完代码再打包，发出去的其实是旧二进制、文件名却写着新版本；
   现在每次都重新编译，并顺带把广告测试台一起编出来。
5) 在「规则管理」里粘贴社区规则（带尾随逗号）会被判「格式错误」并拒绝保存，
   但实际加载逻辑是能读的；现在校验和加载用同一套解析器。
6) 保活服务的 startForeground 没兜异常，系统校验失败时会让进程反复崩溃；
   另外补上了「授权还在、服务却没连上」的检测——这正是「无障碍开着却不跳」
   最难自查的一种情况，现在会写进首页「最近记录」。
7) 内置规则里 oopz 混进了一条弹窗按钮词「以后再」，会在开屏监测窗口内
   误点更新提示之类的按钮，已移除。弹窗样本也补进了回归脚本（19/19 通过）。

■ 上一版重点（v1.3.0）：修「网页类广告（oopz 等）跳不过 / 多次跳过失败居多」
1) 扫描慢到把广告等没了（这是跳过失败的头号原因）
   开屏广告整段只有 5 秒，而原来每扫一次要花 1.3~4.6 秒——
   系统自带的「按文字找节点」在网页里要遍历整棵渲染树，oopz 的广告实测单次 3.2 秒。
   等它返回，广告早播完了，看起来就是「怎么都不跳」。
   现在改成自己遍历一次界面树 + 本地匹配，oopz 实测从 4.6 秒降到 8~59 毫秒。
2) 广告来得很晚就抓不到
   原来「整页遍历」的触发时机是写死的第 0/2/5/9 轮，而 oopz 的广告
   冷启动约 5 秒后才加载出来——那时窗口早就过了，扫描只剩快路径，
   纯文字的「跳过 5」只能靠运气撞上。现在改成每 0.5 秒保证扫一次。
3) App 里的弹窗几乎从来没被关过（这才是「多次跳过」的另一层原因）
   弹窗规则原来只挂在「界面内容发生变化」这个事件上。可很多弹窗是
   叠在一张静止不动的页面上弹出来的，内容没变就没有事件，
   弹窗扫描一次都不会跑，弹层就一直顶在那里。
   另外开屏监测那 8~10 秒内，弹窗规则是被完全跳过的——
   而「开屏广告播完，紧接着弹运营弹层」恰恰是最常见的组合。
   现在弹窗改成由轮询兜底，并且配了弹窗规则的 App 会自动加快轮询。
4) 网页里点「跳过」点了没反应
   网页节点按控件 id 找得到的，旧代码却还在按文字再找一遍，
   白白多等好几秒。现在一次遍历把 id 和文字一起匹配完。

■ 上一版（v1.2.1）：代码体检，修 4 个「看起来配好了却不动」的坑
1) 自检面板卡死 / 偶尔整个服务没反应
   自检按钮原来在主线程读界面树（几百次跨进程调用，网页类界面单次要 3 秒），
   点一下会卡住一两秒，极端情况直接死锁。现在全部挪到独立线程。
2) 「无障碍被一键清理」的提醒永远收不到
   告警用了一个从未创建过的通知渠道，安卓 8 以后会直接丢掉这条通知。
   也就是说最需要提醒你的那个场景，提醒从来没出现过。
3) 悬浮窗权限后给的时候，秒跳不会重挂透明微窗
   后果很隐蔽：你照着首页黄字把悬浮窗打开了、权限全绿，回来还是一个广告都不跳，
   必须重启手机才行。现在回到首页会立刻补挂，后台每 8 秒也会兜底重试。
4) 远程规则强制 https
   规则本身是「在哪个界面点哪里」的指令。明文 http 意味着同一个 WiFi 下
   任何人都能把规则换掉，让你手机上自动点任意位置。现在 http 地址会直接拒绝。
5) 顺带修掉：弹窗规则在网页类界面上能把扫描线程卡住一分钟；
   节点重复回收导致的「配了两条规则只生效一条」；每点一次自检泄漏一个节点。
6) 签名口令不再写在构建脚本里（挪到本机配置），避免有人据此伪造同签名安装包。

■ 上一个版本（v1.2.0）：修「不开探测器就不跳」
   症状：无障碍显示已开启，但一个广告都不跳；
        把自检器 / 探测器打开之后，跳过立刻恢复正常。
   原因有两个，都在系统侧：
   a) 秒跳没有「可见界面」时，系统不给它窗口内容
      安卓判定一个无障碍服务能拿到哪个界面，跟它自己有没有窗口有关。
      旧版只在后台跑，系统把 rootInActiveWindow 一直返回上一个 App 的
      旧界面（有时甚至是桌面），取到的节点全是过期的，自然找不到跳过按钮。
      新版常驻一个 1×1 的透明窗口（看不见、不挡操作、不耗电），
      系统就正常下发当前界面的内容了。
   b) 没有通知权限 → 进程被系统冻结
      安卓对「没有通知、又没在前台」的进程会直接冻结。冻结后无障碍
      开关照样显示「已开启」，但代码一行都不跑。新版把常驻通知改成
      常驻可见（低优先级，不会响），并在首页用黄字提示你补授权。
   c) 另外加了 0.7 秒一次的主动巡检
      有些系统事件会漏发，光等事件通知会一直干等。新版除了等事件，
      还自己定时看一眼当前界面，事件漏了也能跳。
   d) 首页新增「安装体检」
      通知权限 / 悬浮窗 / 电池白名单 三项没配好，首页会用黄字提示，
      点一下直接跳到对应设置页。三项全绿才算配好。

■ 上一个版本（v1.1.0）：修「太灵敏、乱点」
1) 不再把「关闭」当成跳过按钮
   抖音评论区的关闭 ×、浏览器标签页的关闭，无障碍描述都叫「关闭」，
   旧版会把它们当广告点掉。现在只认「跳过 / 关闭广告」这种广告专属词。
2) 浏览器整体不参与识别
   浏览器里没有开屏广告，但「关闭标签页」「新建标签页 +」长得都像跳过按钮。
   现在 Chrome / QQ浏览器 / 小米浏览器 / 夸克 / UC 等一律跳过不扫描。
3) 只有「从桌面冷启动」才做智能识别
   App 内部切页面（进评论区、翻章节、开新对话）不再触发猜测，
   从根上避免点到番茄的「分类 / 点赞」、DeepSeek 的「新对话」。
4) 智能识别要连续两轮看到同一个位置才点
   冷启动瞬间页面还没渲染完，界面看着像开屏广告；等两轮再点就绕过了这个坑。
5) 删掉了「坐标学习」，并自动清理旧版学歪的规则
   旧版会把误点的位置记成坐标规则，之后每次启动都点那个点。
   新版首次启动会自动清掉这些脏数据（日志里显示「已清理 N 条历史学习」）。
6) 微信 / QQ 里跳外部链接不再被强制返回
   小程序、公众号文章跳浏览器属于正常操作，防跳转不再插手；
   浏览器只对短视频 / 小说 / 资讯类 App 的误触跳转才返回。

■ 安装步骤
1) 把 .apk 文件传到手机（微信文件传输助手 / QQ / 数据线 / 网盘都行）。
   ※ 如果传输工具把文件改名成 xxx.apk.1，把后缀 .1 去掉改回 .apk 即可正常安装。
   ※ 或者直接解压本 ZIP，里面的文件名已经是唯一的，不会再被追加数字。

2) 用手机「文件管理」点击这个 .apk 文件。

3) 首次会提示「未知来源应用 / 外部来源应用」，按提示允许。
   路径：设置 → 应用 → 特殊应用权限 → 安装未知应用
        → 选中你用来打开 APK 的那个应用（文件管理 / 浏览器 / 微信）

4) 安装完成后打开「秒跳」，按 App 内引导开启无障碍权限。

5) 若某个 App 的开屏广告没被跳过，把 App 名字发给我，补一条规则即可。

■ 如果提示「应用未安装」或「签名冲突」
   说明手机上已经装过旧版（签名不同），需要先卸载旧的再装：
   长按桌面上的「秒跳」图标 → 卸载 → 再安装本文件。
   （卸载会清空设置，重新开启无障碍权限即可）

■ 装好后必做四步（少一步都可能「无障碍开着却不跳广告」）
   1) 设置 → 无障碍 → 已下载的服务 → 找到「秒跳」→ 打开开关。
      ※ 小米/红米重装后开关不会自动恢复，需要手动关一次再开一次。

   2) 允许通知。打开「秒跳」时会自动弹窗问你，点「始终允许」。
      ※ 这不是为了发广告：没有通知，系统会把秒跳当成后台应用直接冻结，
        无障碍照样显示「已开启」，但一个广告都不会跳。

   3) 允许「显示在其他应用上层」（悬浮窗）。
      首页状态栏会提示，点一下就能跳过去开。

   4) 电池省电策略 → 选「无限制」；自启动 → 打开。
      路径：设置 → 应用 → 应用管理 → 秒跳
      ※ 默认的「仅在使用中允许」会在你切走一分钟后冻结进程。

   这四项首页都会用黄字提示，点黄字直接跳到对应设置。全部变绿就说明配好了。

■ 广告测试台（ZIP 里另一个 APK，可选装）
   叫「广告测试台」，共 19 个样本：14 种人造开屏广告 + 1 个正常内容页对照组
   + 1 个弹窗样本 + 3 个「绝对不许点」的负向样本。
   打开后点任意一条就能看到对应的广告形态，用来验证跳过是否生效。
   三个「不该被点」的样本：番茄式首页、抖音式评论区、DeepSeek 式欢迎页。
   弹窗样本：内容页上浮出一个「会员特惠」弹层，用来验证 App 内弹窗的自动关闭。

■ 如果某个 App 不跳
   打开「秒跳」，看页面底部的「最近记录」：
   · 「取不到 XX 的界面」→ 悬浮窗权限或省电策略没配好（回到上面第 3、4 步）
   · 「未找到跳过按钮：XX」→ 这个 App 的按钮是自绘的，把 App 名字发我补规则
   · 「跳过 XX · 按钮文字」→ 正常跳过

■ 文件校验（可选，确认传输没损坏）
SHA-256: ${SHA}
（完整列表见同目录 .sha256 文件）

■ 这个 App 做什么
监听你打开的 App，在开屏广告出现时自动点「跳过」。
需要在系统设置里开启无障碍权限，仅本机使用，不联网上传任何信息。
EOF

echo "[4/4] 打包 ZIP ..."
# 广告测试台也一起打进去（可选装，用来验证跳过效果）
SAMPLE_APK="$PROJ_DIR/adsample/build/outputs/apk/debug/adsample-debug.apk"
SAMPLE_NAME=""
if [[ -f "$SAMPLE_APK" ]]; then
  SAMPLE_NAME="广告测试台-19种样本-${STAMP}.apk"
  cp -f "$SAMPLE_APK" "$SAMPLE_NAME"
  echo "      附带广告测试台：$SAMPLE_NAME"
fi

rm -f "$ZIPNAME"
FILES_TO_ZIP=("$FILENAME" "$FILENAME.sha256" "安装说明.txt")
[[ -n "$SAMPLE_NAME" ]] && FILES_TO_ZIP+=("$SAMPLE_NAME")

if command -v zip >/dev/null 2>&1; then
  zip -q "$ZIPNAME" "${FILES_TO_ZIP[@]}"
elif command -v python >/dev/null 2>&1; then
  python -c "
import zipfile
z = zipfile.ZipFile(r'$ZIPNAME', 'w', zipfile.ZIP_DEFLATED)
for f in [r'$FILENAME', r'$FILENAME.sha256', r'安装说明.txt'] + ([r'$SAMPLE_NAME'] if r'$SAMPLE_NAME' else []):
    z.write(f, f)
z.close()
"
elif command -v python3 >/dev/null 2>&1; then
  python3 -c "
import zipfile
z = zipfile.ZipFile(r'$ZIPNAME', 'w', zipfile.ZIP_DEFLATED)
for f in [r'$FILENAME', r'$FILENAME.sha256', r'安装说明.txt'] + ([r'$SAMPLE_NAME'] if r'$SAMPLE_NAME' else []):
    z.write(f, f)
z.close()
"
else
  echo "      (无 zip/python，跳过 ZIP，仅保留单个 APK)"
fi

echo
echo "  APK : $OUT_DIR/$FILENAME"
[[ -f "$ZIPNAME" ]] && echo "  ZIP : $OUT_DIR/$ZIPNAME"
echo "  大小 : $(du -h "$FILENAME" | cut -f1)"
echo "  哈希 : $HASH"
echo
echo "发这个文件名出去就不会再出现 .1 后缀了。"
